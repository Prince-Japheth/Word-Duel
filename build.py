#!/usr/bin/env python3
"""Build Word Duel.

1. Generates the dictionary ModuleScripts in src/ServerStorage/Words/ from a word list.
2. Packs everything under src/ into WordDuel.rbxlx (open it in Roblox Studio).

Naming (same as Rojo):
  Foo.server.lua -> Script, Foo.client.lua -> LocalScript, Foo.lua -> ModuleScript, folder -> Folder.
  Top-level folders in src/ are services (ServerScriptService, ReplicatedStorage, ...).

Usage: python3 build.py [--words path/to/wordlist.txt]   (default: wordlists/enable1.txt)
"""
import argparse
import os
import re
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, "src")
OUT = os.path.join(ROOT, "WordDuel.rbxlx")
WORDS_DIR = os.path.join(SRC, "ServerStorage", "Words")
EXTRA_WORDS = os.path.join(ROOT, "words_extra.txt")
START_WORDS = os.path.join(ROOT, "words_start.txt")
BLOCK_WORDS = os.path.join(ROOT, "words_block.txt")
COMMON_WORDS = os.path.join(ROOT, "wordlists", "popular.txt")

MIN_LEN, MAX_LEN = 3, 10


def read_list(path):
    if not os.path.exists(path):
        return set()
    with open(path, encoding="utf-8", errors="ignore") as f:
        return {w.strip().lower() for w in f if re.fullmatch(r"[A-Za-z]+", w.strip())}


def build_words(source):
    base = set()
    with open(source, encoding="utf-8", errors="ignore") as f:
        for line in f:
            w = line.strip()
            if re.fullmatch(r"[a-z]+", w) and MIN_LEN <= len(w) <= MAX_LEN:
                base.add(w)
    words = set(base)  # ENABLE already has plurals and verb forms
    words |= {w for w in read_list(EXTRA_WORDS) if MIN_LEN <= len(w) <= MAX_LEN}
    # Start words: common everyday words, also added to the dictionary if missing.
    start = set()
    if os.path.exists(START_WORDS):
        with open(START_WORDS, encoding="utf-8") as f:
            start = {w.lower() for w in re.findall(r"[A-Za-z]+", f.read()) if MIN_LEN <= len(w) <= MAX_LEN}
    # Common list (popular.txt = ENABLE words people actually use): steers bot moves and Help hints.
    # Start words stay the hand-picked list only: popular.txt still has words like FOP, AUK, AGA.
    common = start | {w for w in read_list(COMMON_WORDS) if MIN_LEN <= len(w) <= MAX_LEN and w in base}
    words |= common
    words -= read_list(BLOCK_WORDS)

    os.makedirs(WORDS_DIR, exist_ok=True)
    for name in os.listdir(WORDS_DIR):
        if name.startswith("Words") and name.endswith(".lua"):
            os.remove(os.path.join(WORDS_DIR, name))
    counts = {}
    for length in range(MIN_LEN, MAX_LEN + 1):
        group = sorted(w for w in words if len(w) == length)
        counts[length] = len(group)
        # chunk so no single script source gets huge
        chunk = 6000
        for i in range(0, len(group), chunk):
            part = group[i : i + chunk]
            path = os.path.join(WORDS_DIR, f"Words{length}_{i // chunk + 1}.lua")
            with open(path, "w") as f:
                f.write(f"-- generated by build.py: {len(part)} words of length {length}\n")
                f.write('return "' + " ".join(part) + '"\n')

    start &= words  # drop anything in the block list
    common &= words

    def write_lengths(name, group_set, note):
        with open(os.path.join(SRC, "ServerStorage", name + ".lua"), "w") as f:
            f.write(f"-- generated by build.py: {len(group_set)} {note}\n")
            f.write("return {\n")
            for length in range(MIN_LEN, MAX_LEN + 1):
                group = sorted(w for w in group_set if len(w) == length)
                f.write(f'\t[{length}] = "' + " ".join(group) + '",\n')
            f.write("}\n")

    write_lengths("StartWords", start, "hand-picked start words (words_start.txt)")
    write_lengths("CommonWords", common, "everyday words (words_start.txt + wordlists/popular.txt)")
    print("start words by length:", {n: sum(1 for w in start if len(w) == n) for n in range(MIN_LEN, MAX_LEN + 1)})
    print("common words:", len(common))
    return counts


# ---------------------------------------------------------------- rbxlx packing
_ref = 0


def next_ref():
    global _ref
    _ref += 1
    return f"RBX{_ref:08X}"


def cdata(text):
    return "<![CDATA[" + text.replace("]]>", "]]]]><![CDATA[>") + "]]>"


def script_item(path, name, cls):
    with open(path, encoding="utf-8") as f:
        source = f.read()
    return (
        f'<Item class="{cls}" referent="{next_ref()}"><Properties>'
        f'<string name="Name">{escape(name)}</string>'
        f'<ProtectedString name="Source">{cdata(source)}</ProtectedString>'
        f"</Properties></Item>"
    )


def dir_items(path):
    parts = []
    for entry in sorted(os.listdir(path)):
        full = os.path.join(path, entry)
        if entry.startswith("."):
            continue
        if os.path.isdir(full):
            parts.append(
                f'<Item class="Folder" referent="{next_ref()}"><Properties>'
                f'<string name="Name">{escape(entry)}</string></Properties>'
                + "".join(dir_items(full))
                + "</Item>"
            )
        elif entry.endswith(".server.lua"):
            parts.append(script_item(full, entry[: -len(".server.lua")], "Script"))
        elif entry.endswith(".client.lua"):
            parts.append(script_item(full, entry[: -len(".client.lua")], "LocalScript"))
        elif entry.endswith(".lua"):
            parts.append(script_item(full, entry[: -len(".lua")], "ModuleScript"))
    return parts


# StarterPlayer's StarterPlayerScripts is a special container class
CONTAINER_CLASS = {"StarterPlayerScripts": "StarterPlayerScripts", "StarterCharacterScripts": "StarterCharacterScripts"}


def service_item(name, path):
    children = []
    for entry in sorted(os.listdir(path)):
        full = os.path.join(path, entry)
        if os.path.isdir(full) and entry in CONTAINER_CLASS:
            children.append(
                f'<Item class="{CONTAINER_CLASS[entry]}" referent="{next_ref()}"><Properties>'
                f'<string name="Name">{entry}</string></Properties>'
                + "".join(dir_items(full))
                + "</Item>"
            )
        elif os.path.isdir(full):
            children.append(
                f'<Item class="Folder" referent="{next_ref()}"><Properties>'
                f'<string name="Name">{escape(entry)}</string></Properties>'
                + "".join(dir_items(full))
                + "</Item>"
            )
        else:
            children.extend(dir_items_single(full, entry))
    return (
        f'<Item class="{name}" referent="{next_ref()}"><Properties>'
        f'<string name="Name">{name}</string></Properties>' + "".join(children) + "</Item>"
    )


def dir_items_single(full, entry):
    if entry.endswith(".server.lua"):
        return [script_item(full, entry[: -len(".server.lua")], "Script")]
    if entry.endswith(".client.lua"):
        return [script_item(full, entry[: -len(".client.lua")], "LocalScript")]
    if entry.endswith(".lua"):
        return [script_item(full, entry[: -len(".lua")], "ModuleScript")]
    return []


def build_place():
    items = []
    for name in sorted(os.listdir(SRC)):
        full = os.path.join(SRC, name)
        if os.path.isdir(full):
            items.append(service_item(name, full))
    xml = '<roblox xmlns:xmime="http://www.w3.org/2005/05/xmlmime" version="4">' + "".join(items) + "</roblox>"
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(xml)
    return os.path.getsize(OUT)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--words", default=os.path.join(ROOT, "wordlists", "enable1.txt"))
    args = ap.parse_args()
    counts = build_words(args.words)
    print("words by length:", counts, "total", sum(counts.values()))
    size = build_place()
    print(f"wrote {OUT} ({size // 1024} KB)")
